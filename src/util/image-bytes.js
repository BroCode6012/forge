/**
 * image-bytes.js — decide whether raw bytes are safe to hand to an image decoder.
 *
 * WHY THIS EXISTS
 * @napi-rs/canvas does not merely reject some inputs — it SEGFAULTS on them.
 * Measured on 0.1.95: a TIFF kills the process with exit 139, no exception, no
 * stack. Every one of our decode call sites is wrapped in try/catch, and a
 * try/catch cannot see a segfault. So a single downloaded .tif (or a .jpg URL
 * that actually serves TIFF bytes) takes the entire build down with no error
 * message at all — the worst possible failure mode: silent and unattributable.
 *
 * Measured behaviour of the decoder, one isolated process per format:
 *   jpeg png webp gif bmp avif svg -> decode fine
 *   ppm, mp4, html                 -> throw "Unsupported image type" (safe)
 *   tiff                           -> *** process death, uncatchable ***
 *
 * So this is a POSITIVE ALLOWLIST, not a tiff blocklist: anything we have not
 * actually proven safe goes down the ffmpeg path instead. ffmpeg is a far more
 * permissive decoder and is already a dependency, so the fallback usually
 * SUCCEEDS — a video container handed to us as a "frame" gets turned into a
 * real JPEG rather than being lost.
 */

const fs = require('fs');

/** Bytes we need to make a confident call. ftyp brands live at offset 8-12. */
const SNIFF_BYTES = 16;

/**
 * ISO base-media brands that are genuinely still images the decoder handles.
 * Anything else with an `ftyp` box (isom, mp42, qt) is a VIDEO container — it
 * throws safely today, but ffmpeg can actually pull a frame out of it, so we
 * deliberately route it to ffmpeg rather than to a guaranteed failure.
 */
const STILL_IMAGE_BRANDS = new Set(['avif', 'avis', 'heic', 'heix', 'heim', 'heis', 'hevc', 'hevx', 'mif1', 'msf1']);

/**
 * @param {Buffer|string} input raw bytes, or a path to read the first bytes of
 * @returns {Buffer|null} the leading bytes, or null if unreadable
 */
function _head(input) {
    if (Buffer.isBuffer(input)) return input.subarray(0, SNIFF_BYTES);
    if (typeof input !== 'string' || !input) return null;
    // A data: URI is generated by us, never fetched — treat as trusted.
    if (input.startsWith('data:')) return null;
    let fd;
    try {
        fd = fs.openSync(input, 'r');
        const buf = Buffer.alloc(SNIFF_BYTES);
        const read = fs.readSync(fd, buf, 0, SNIFF_BYTES, 0);
        return buf.subarray(0, read);
    } catch (_) {
        return null;
    } finally {
        if (fd !== undefined) { try { fs.closeSync(fd); } catch (_) { /* already gone */ } }
    }
}

/**
 * Identify the byte format. Returns a short lowercase tag, or null when the
 * bytes match nothing we recognise.
 * @param {Buffer|string} input
 * @returns {string|null}
 */
function sniffImageFormat(input) {
    const b = _head(input);
    if (!b || b.length < 4) return null;

    if (b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return 'jpeg';
    if (b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47) return 'png';
    if (b[0] === 0x47 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x38) return 'gif';
    if (b[0] === 0x42 && b[1] === 0x4d) return 'bmp';
    // TIFF — the crasher. Named explicitly so the reason is greppable.
    if ((b[0] === 0x49 && b[1] === 0x49 && b[2] === 0x2a && b[3] === 0x00)
        || (b[0] === 0x4d && b[1] === 0x4d && b[2] === 0x00 && b[3] === 0x2a)) return 'tiff';
    if (b.length >= 12 && b.subarray(0, 4).toString('latin1') === 'RIFF'
        && b.subarray(8, 12).toString('latin1') === 'WEBP') return 'webp';
    if (b.length >= 12 && b.subarray(4, 8).toString('latin1') === 'ftyp') {
        const brand = b.subarray(8, 12).toString('latin1').toLowerCase();
        return STILL_IMAGE_BRANDS.has(brand) ? 'avif' : 'iso-video';
    }
    // SVG/XML/HTML all start with '<'. Only a real <svg root is an image.
    if (b[0] === 0x3c) {
        const txt = b.toString('latin1').toLowerCase();
        if (txt.includes('<svg') || txt.includes('<?xml')) return 'svg';
        return 'markup';
    }
    return null;
}

/**
 * Is it safe to pass these bytes to @napi-rs/canvas?
 *
 * Conservative on purpose: unknown -> false. A false negative costs one ffmpeg
 * call; a false positive costs the whole build process.
 *
 * @param {Buffer|string} input raw bytes, or a file path
 * @returns {boolean}
 */
function isCanvasSafeImage(input) {
    // A path we could not read at all: let the caller's own error handling run
    // rather than inventing a decode failure here.
    if (typeof input === 'string' && !Buffer.isBuffer(input)) {
        const head = _head(input);
        if (head === null) return true;
    }
    const fmt = sniffImageFormat(input);
    return fmt === 'jpeg' || fmt === 'png' || fmt === 'gif' || fmt === 'bmp'
        || fmt === 'webp' || fmt === 'avif' || fmt === 'svg';
}

module.exports = { sniffImageFormat, isCanvasSafeImage };
