'use strict';

/**
 * LIVE PROVIDER SCOREBOARD — the media downloader's in-run memory.
 *
 * The problem this exists to solve: a build can open the same provider on scene
 * after scene, watch it lose every single time, and still open it first on the
 * next scene. In the Jul-29 diagnosis build, Pixabay was opened 7 times and won
 * 0 scenes; nothing in the system ever noticed. Meanwhile the topic
 * (`explainer.diy`) declares `youtube` as its #1 source, and YouTube was only
 * opened on 12 of 44 scenes.
 *
 * So this module keeps one thing: what actually happened, per provider, during
 * THIS build. Providers that keep winning rise; providers that keep losing sink.
 * It is deliberately evidence-only — it never bans a provider and never invents
 * an ordering of its own. It nudges whatever order it is handed.
 *
 * Why it is topic-adaptive without a single `if (niche === ...)`:
 * the evidence it collects is generated by this topic's scenes, this topic's
 * queries and this topic's visual bar. A DIY build teaches it that YouTube
 * delivers; a news build teaches it that stock delivers. Same code, different
 * conclusion, learned from data rather than declared in a table.
 *
 * State is module-level, which means per build child-process — exactly the
 * lifetime we want. Nothing persists across builds on purpose: a scoreboard
 * learned on a nature documentary must not silently steer a crime video.
 */

/** @typedef {'video'|'image'} MediaType */

/**
 * key = `${mediaType}:${providerKey}`
 * @type {Map<string, {opens:number, wins:number, losses:number, reasons:Map<string,number>}>}
 */
const _stats = new Map();

function _key(mediaType, providerKey) {
    return `${String(mediaType || 'video')}:${String(providerKey || '').toLowerCase()}`;
}

function _slot(mediaType, providerKey) {
    const k = _key(mediaType, providerKey);
    let slot = _stats.get(k);
    if (!slot) {
        slot = { opens: 0, wins: 0, losses: 0, reasons: new Map() };
        _stats.set(k, slot);
    }
    return slot;
}

/** A provider was actually searched/opened for a scene. */
function recordOpen(mediaType, providerKey) {
    if (!providerKey) return;
    _slot(mediaType, providerKey).opens += 1;
}

/** This provider supplied the media the scene ended up keeping. */
function recordWin(mediaType, providerKey) {
    if (!providerKey) return;
    _slot(mediaType, providerKey).wins += 1;
}

/** This provider was opened for a scene and produced nothing usable. */
function recordLoss(mediaType, providerKey, reason) {
    if (!providerKey) return;
    const slot = _slot(mediaType, providerKey);
    slot.losses += 1;
    const r = String(reason || 'no usable candidate').slice(0, 60);
    slot.reasons.set(r, (slot.reasons.get(r) || 0) + 1);
}

/**
 * Laplace-smoothed win rate. Smoothing matters: without it a provider that won
 * its only opening looks perfect (1.0) and a provider that lost its only
 * opening looks hopeless (0.0), and we would reorder the whole build off one
 * coin flip. With +1/+2 smoothing an unproven provider sits at 0.5 (neutral)
 * and only sustained evidence moves it.
 *
 * @returns {number} 0..1
 */
function winRate(mediaType, providerKey) {
    const slot = _stats.get(_key(mediaType, providerKey));
    if (!slot || slot.opens <= 0) return 0.5;
    return (slot.wins + 1) / (slot.opens + 2);
}

/** How much evidence do we have on this provider? */
function opens(mediaType, providerKey) {
    return _stats.get(_key(mediaType, providerKey))?.opens || 0;
}

/**
 * Below this many openings we do not act on a provider's record at all — one
 * or two failures are noise, not a pattern.
 */
const MIN_EVIDENCE_OPENS = 3;

/**
 * A provider may not move more than this many places from where it was handed
 * to us. The Media Agent reasons per scene and sees things this scoreboard
 * cannot (what the scene is actually about); its ordering stays the authority.
 * This is a correction, not a replacement — a provider with a terrible record
 * sinks, but it sinks gradually and it is never removed.
 */
const MAX_SHIFT = 2;

/**
 * Only swap two neighbours when the gap between their records is big enough to
 * mean something. Without this, noise reshuffles the mission every scene.
 */
const MIN_RATE_GAP = 0.10;

/**
 * Re-rank a provider order using this build's evidence.
 *
 * Implemented as MAX_SHIFT bubble passes rather than a full sort, because the
 * bound then holds *by construction*: each pass moves any provider at most one
 * place, so after MAX_SHIFT passes nothing has travelled further than that.
 * (A full sort plus a post-hoc clamp cannot honour the bound — if everything
 * above a proven loser rises, the loser is pushed to the bottom no matter what
 * the clamp says.)
 *
 * Rules:
 *  - a neighbour swap needs a MIN_RATE_GAP difference in smoothed win rate AND
 *    at least one of the two providers to have real evidence behind it;
 *  - providers with less than MIN_EVIDENCE_OPENS openings score a neutral 0.5,
 *    so they neither rise nor sink on nothing;
 *  - nothing is ever dropped. The result is always a permutation of the input.
 *
 * @param {string[]} order incoming provider keys, best-first
 * @param {MediaType} mediaType
 * @returns {{order:string[], moved:Array<{provider:string, from:number, to:number, winRate:number, opens:number}>}}
 */
function adjustOrder(order, mediaType) {
    const incoming = Array.isArray(order) ? order.filter(Boolean).map(k => String(k).toLowerCase()) : [];
    if (incoming.length < 2) return { order: incoming, moved: [] };

    const arr = incoming.map((provider, index) => {
        const evidence = opens(mediaType, provider);
        const rate = evidence >= MIN_EVIDENCE_OPENS ? winRate(mediaType, provider) : 0.5;
        return { provider, index, evidence, rate };
    });

    for (let pass = 0; pass < MAX_SHIFT; pass++) {
        let swapped = false;
        for (let i = 0; i < arr.length - 1; i++) {
            const a = arr[i];
            const b = arr[i + 1];
            const proven = a.evidence >= MIN_EVIDENCE_OPENS || b.evidence >= MIN_EVIDENCE_OPENS;
            if (proven && (b.rate - a.rate) >= MIN_RATE_GAP) {
                arr[i] = b;
                arr[i + 1] = a;
                swapped = true;
                i++; // one move per element per pass, so the bound holds
            }
        }
        if (!swapped) break;
    }

    const moved = [];
    arr.forEach((entry, to) => {
        if (to !== entry.index && entry.evidence >= MIN_EVIDENCE_OPENS) {
            moved.push({
                provider: entry.provider,
                from: entry.index,
                to,
                winRate: Number(winRate(mediaType, entry.provider).toFixed(2)),
                opens: entry.evidence,
            });
        }
    });

    return { order: arr.map(e => e.provider), moved };
}

/**
 * Human-readable end-of-build summary, so a log reader can see in one line why
 * the ordering drifted. Returns null when nothing was recorded.
 */
function summary() {
    if (_stats.size === 0) return null;
    const rows = [];
    for (const [k, slot] of _stats.entries()) {
        const [mediaType, provider] = k.split(':');
        rows.push({
            mediaType,
            provider,
            opens: slot.opens,
            wins: slot.wins,
            losses: slot.losses,
            winRate: slot.opens > 0 ? Number((slot.wins / slot.opens).toFixed(2)) : null,
            topReason: [...slot.reasons.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] || null,
        });
    }
    rows.sort((a, b) => (b.opens - a.opens) || a.provider.localeCompare(b.provider));
    return rows;
}

/** Reset all evidence. Used by tests and by a fresh build in-process. */
function reset() {
    _stats.clear();
}

module.exports = {
    recordOpen,
    recordWin,
    recordLoss,
    winRate,
    opens,
    adjustOrder,
    summary,
    reset,
    MIN_EVIDENCE_OPENS,
    MAX_SHIFT,
};
